// powershellCompletion: argument completer registered against the native
// `netcheck` command. PowerShell's completion model is closer to zsh than
// bash — every suggestion comes back as a CompletionResult with a tooltip.
var powershellCompletion = `# PowerShell completion for netcheck — generated by ` + "`netcheck completion powershell`" + `
# Add to $PROFILE to persist across sessions, or pipe through Invoke-Expression
# for one-shot setup.

Register-ArgumentCompleter -Native -CommandName netcheck -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $commands = @(
        @{ Name = 'menu';       Tooltip = 'interactive menu' }
        @{ Name = 'app';        Tooltip = 'run the local web app' }
        @{ Name = 'dns';        Tooltip = 'compare DNS resolvers' }
        @{ Name = 'route';      Tooltip = 'trace the network path with per-hop ASN' }
        @{ Name = 'ip';         Tooltip = 'IP ownership, RDAP, reverse DNS, CDN hints' }
        @{ Name = 'headers';    Tooltip = 'security-header report card' }
        @{ Name = 'tech';       Tooltip = 'fingerprint CMS / framework / server / CDN' }
        @{ Name = 'subs';       Tooltip = 'enumerate subdomains via CT logs' }
        @{ Name = 'reverse';    Tooltip = 'other hostnames on this IP' }
        @{ Name = 'arch';       Tooltip = 'Wayback Machine snapshots' }
        @{ Name = 'whois';      Tooltip = 'registrar lookup via RDAP' }
        @{ Name = 'tls';        Tooltip = 'TLS protocol+cipher audit (ACTIVE)' }
        @{ Name = 'takeover';   Tooltip = 'subdomain-takeover check (ACTIVE)' }
        @{ Name = 'ports';      Tooltip = 'TCP connect scan (ACTIVE)' }
        @{ Name = 'enum';       Tooltip = 'HTTP path enumeration (ACTIVE)' }
        @{ Name = 'audit';      Tooltip = 'aggregate report (passive + optional active)' }
        @{ Name = 'config';     Tooltip = 'print active config' }
        @{ Name = 'completion'; Tooltip = 'print shell completion script' }
        @{ Name = 'help';       Tooltip = 'show help' }
        @{ Name = 'version';    Tooltip = 'show version' }
    )

    # Tokenize what the user has typed so far. Element 0 is "netcheck".
    $tokens = $commandAst.CommandElements | ForEach-Object { $_.ToString() }

    if ($tokens.Count -le 2) {
        # Completing the first positional — the subcommand name.
        $commands |
            Where-Object { $_.Name -like "$wordToComplete*" } |
            ForEach-Object {
                [System.Management.Automation.CompletionResult]::new(
                    $_.Name, $_.Name, 'ParameterValue', $_.Tooltip
                )
            }
        return
    }

    if ($tokens[1] -eq 'completion' -and $tokens.Count -le 3) {
        @('bash', 'zsh', 'fish', 'powershell') |
            Where-Object { $_ -like "$wordToComplete*" } |
            ForEach-Object {
                [System.Management.Automation.CompletionResult]::new(
                    $_, $_, 'ParameterValue', "shell: $_"
                )
            }
        return
    }

    # --output values.
    $prev = if ($tokens.Count -ge 2) { $tokens[-2] } else { '' }
    if ($prev -eq '--output' -or $prev -eq '-output') {
        @('text', 'json', 'markdown', 'html') |
            Where-Object { $_ -like "$wordToComplete*" } |
            ForEach-Object {
                [System.Management.Automation.CompletionResult]::new(
                    $_, $_, 'ParameterValue', "output format: $_"
                )
            }
    }
}
`
