// bashCompletion: minimal, only completes the first positional. After that we
// fall through to bash's default filename completion, which is the right
// behaviour for `netcheck audit <target>` style invocations where the second
// arg is a hostname or URL (and bash can't introspect those anyway).
var bashCompletion = `# bash completion for netcheck — generated by ` + "`netcheck completion bash`" + `
_netcheck() {
    local cur prev
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"

    # Only complete the subcommand name (first positional).
    if [ "$COMP_CWORD" -eq 1 ]; then
        local cmds="menu app dns route ip headers tech subs reverse arch whois tls takeover ports enum audit config completion help version"
        COMPREPLY=( $(compgen -W "$cmds" -- "$cur") )
        return 0
    fi

    # Complete shell names after ` + "`netcheck completion`" + `.
    if [ "$COMP_CWORD" -eq 2 ] && [ "${COMP_WORDS[1]}" = "completion" ]; then
        COMPREPLY=( $(compgen -W "bash zsh fish powershell" -- "$cur") )
        return 0
    fi

    # Complete --output values.
    if [ "$prev" = "--output" ] || [ "$prev" = "-output" ]; then
        COMPREPLY=( $(compgen -W "text json markdown html" -- "$cur") )
        return 0
    fi

    # Otherwise leave it to bash's default (filenames, useful for --config etc).
    return 0
}
complete -F _netcheck netcheck
`

