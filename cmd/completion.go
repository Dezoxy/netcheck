// RunCompletion prints a shell-completion script for the requested shell to
// stdout. Returns a process exit code.
//
// netcheck doesn't use cobra (it uses the stdlib `flag` package), so the
// completion scripts are hand-written. They only complete the top-level
// subcommand name today — enough to get tab-complete on `netcheck d<TAB>` →
// `netcheck dns`. Flag completion (--output text|json|markdown|html,
// --config <path>, etc.) is not implemented; if/when someone asks, the
// natural upgrade is per-shell flag tables — not a cobra migration.
//
// Install one-liners (also in `netcheck completion --help`):
//
//	bash:        netcheck completion bash       > /etc/bash_completion.d/netcheck
//	zsh:         netcheck completion zsh        > "${fpath[1]}/_netcheck"
//	fish:        netcheck completion fish       > ~/.config/fish/completions/netcheck.fish
//	powershell:  netcheck completion powershell | Out-String | Invoke-Expression
func RunCompletion(args []string) int {
	if len(args) == 0 || args[0] == "-h" || args[0] == "--help" || args[0] == "help" {
		printCompletionUsage(os.Stderr)
		if len(args) == 0 {
			return 2
		}
		return 0
	}
	switch args[0] {
	case "bash":
		fmt.Print(bashCompletion)
	case "zsh":
		fmt.Print(zshCompletion)
	case "fish":
		fmt.Print(fishCompletion)
	case "powershell", "pwsh":
		fmt.Print(powershellCompletion)
	default:
		fmt.Fprintf(os.Stderr, "unknown shell %q\n\n", args[0])
		printCompletionUsage(os.Stderr)
		return 2
	}
	return 0
}

func printCompletionUsage(w io.Writer) {
	fmt.Fprintln(w, "usage: netcheck completion {bash|zsh|fish|powershell}")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "Prints a shell-completion script for the requested shell to stdout.")
	fmt.Fprintln(w, "Pipe or redirect it into the right place for your shell:")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "  bash (system-wide):")
	fmt.Fprintln(w, "    netcheck completion bash | sudo tee /etc/bash_completion.d/netcheck >/dev/null")
	fmt.Fprintln(w, "  bash (per-user):")
	fmt.Fprintln(w, "    netcheck completion bash > ~/.local/share/bash-completion/completions/netcheck")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "  zsh (add a dir to fpath if needed):")
	fmt.Fprintln(w, `    netcheck completion zsh > "${fpath[1]}/_netcheck"`)
	fmt.Fprintln(w, "    # then in a fresh shell, autoload -Uz compinit && compinit")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "  fish:")
	fmt.Fprintln(w, "    netcheck completion fish > ~/.config/fish/completions/netcheck.fish")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "  powershell (current session only — add to $PROFILE to persist):")
	fmt.Fprintln(w, "    netcheck completion powershell | Out-String | Invoke-Expression")
}

